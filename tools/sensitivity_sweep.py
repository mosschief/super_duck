#!/usr/bin/env python3
"""
One-factor-at-a-time sensitivity of the randomized-robot weak spots (`crouch_stand`, `brake_settle`): each sim-to-real
factor is swept over its `RealismConfig` range with every other factor held at nominal (sensor noise on), so the
factor that breaks a scenario stands out.

Writes reports/sensitivity.md. Usage: python3 tools/sensitivity_sweep.py [-k crouch]
"""
import argparse
import contextlib
import dataclasses
import io
import math
import pathlib
import re
import sys
from concurrent.futures import ProcessPoolExecutor

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import simulate_wheeled_duck as swd  # noqa: E402
import test_scenarios as T  # noqa: E402

NOMINAL = dict(friction=1.25, trunk_mass_scale=1.0, trunk_com_shift_m=0.0, motor_strength=1.0, latency_ms=0.4,
               gyro_bias_dps=0.0)
FACTORS = {
    "friction": [0.8, 0.9, 1.0, 1.1, 1.25],
    "trunk_mass_scale": [0.9, 0.95, 1.0, 1.05, 1.1],
    "trunk_com_shift_m": [-0.008, -0.004, 0.0, 0.004, 0.008],
    "motor_strength": [0.9, 0.95, 1.0, 1.05],
    "latency_ms": [0.25, 0.4, 0.55],
    "gyro_bias_dps": [-0.5, -0.25, 0.0, 0.25, 0.5],
}
SCENARIOS = {"crouch_stand": (T.crouch_stand, r"wander ([\d.]+) cm", "wander (cm, pass < 8)"),
             "brake_settle": (T.brake_settle, r"roll-back ([\d.]+) cm, final offset from stop point ([\d.]+) cm",
                              "roll-back / settle offset (cm, pass < 6 / < 3)")}


def point(v):
    return (v, v)


def evaluate(job):
    scenario, factor, value = job
    p = dict(NOMINAL, **{factor: value})
    cfg = dataclasses.replace(swd.RealismConfig(), friction=point(p["friction"]),
                              trunk_mass_scale=point(p["trunk_mass_scale"]),
                              trunk_com_shift_m=point(p["trunk_com_shift_m"]),
                              motor_strength=point(p["motor_strength"]), mcu_latency_ms=point(p["latency_ms"]))
    T.REALISM_CFG = cfg
    base = swd.SimToReal

    class Fixed(base):
        def __init__(self, *a, **kw):
            super().__init__(*a, **kw)
            self.gyro_bias = np.radians([0.0, p["gyro_bias_dps"], 0.0])

    T.swd.SimToReal = Fixed
    fn, pattern, _ = SCENARIOS[scenario]
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            ok, fell, msg = fn(0)
    finally:
        T.swd.SimToReal = base
    m = re.search(pattern, msg)
    return scenario, factor, value, ok, fell, (" / ".join(m.groups()) if m else msg)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-k", default="")
    args = ap.parse_args()
    jobs = [(s, f, v) for s in SCENARIOS if args.k in s for f, vals in FACTORS.items() for v in vals]
    with ProcessPoolExecutor() as ex:
        res = list(ex.map(evaluate, jobs))
    L = ["# Sensitivity Sweep", "",
         "Generated by `tools/sensitivity_sweep.py`: each factor swept alone, the others at nominal (friction 1.25, "
         "nominal mass / CoM / motors, 0.4 ms latency, no gyro bias), sensor noise on (seed 0).", ""]
    for s in SCENARIOS:
        rows = [r for r in res if r[0] == s]
        if not rows:
            continue
        L += [f"## {s}: {SCENARIOS[s][2]}", "", "| Factor | " + " | ".join(f"v{i + 1}" for i in range(5)) + " |",
              "| :--- |" + " :--- |" * 5]
        for f, vals in FACTORS.items():
            cells = [f"{v:g}: **{m}**{'' if ok else ' ✗'}" for _, ff, v, ok, fell, m in rows if ff == f]
            L.append(f"| {f} | " + " | ".join(cells + [""] * (5 - len(cells))) + " |")
        L.append("")
    out = ROOT / "reports" / "sensitivity.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
