#!/usr/bin/env python3
"""Writes the C++ controller's `Config` for a robot profile into a firmware header.

The values come from the Python controller (class constants, profile, LQR gains from scipy's Riccati solver),
exactly as the sim hands them to the C++ controller (`duck.cpp_controller.config_values`), so the firmware runs the
numbers the test suites passed with. Doubles are written with Python's shortest round-trip repr, so the compiler
reads back the identical bits.

  python3 tools/export_firmware_config.py            # -> firmware/controller/config_gim6010.hpp
  python3 tools/export_firmware_config.py --check    # exit 1 if the header is out of date (CI)
"""

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from duck.cpp_controller import config_values  # noqa: E402
from duck.robot import DEFAULT_ROBOT, PROFILES  # noqa: E402


def header(robot: str) -> str:
    values = config_values(PROFILES[robot])
    width = max(map(len, values))
    lines = [
        f"// Generated by tools/export_firmware_config.py from duck/controller.py and the '{robot}' robot profile.",
        "// Do not edit: change the Python controller or the profile, then re-run the script.",
        "#pragma once",
        "",
        '#include "duck_controller.hpp"',
        "",
        "namespace duck {",
        "",
        f"constexpr Config kConfig{robot.capitalize()} = {{",
    ]
    lines += [f"    {v!r},{' ' * (24 - len(repr(v)))}// {name:{width}s}" for name, v in values.items()]
    lines += ["};", "", "}  // namespace duck", ""]
    return "\n".join(line.rstrip() for line in lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--robot", choices=sorted(PROFILES), default=DEFAULT_ROBOT)
    ap.add_argument("--check", action="store_true", help="fail if the header on disk differs")
    args = ap.parse_args()
    out = ROOT / "firmware" / "controller" / f"config_{args.robot}.hpp"
    text = header(args.robot)
    if args.check:
        if not out.exists() or out.read_text() != text:
            print(f"{out.relative_to(ROOT)} is out of date: run tools/export_firmware_config.py --robot {args.robot}")
            return 1
        print(f"{out.relative_to(ROOT)} is up to date")
        return 0
    out.write_text(text)
    print(f"-> {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
