"""Sweep the left leg's joints through their MJCF ranges and report collisions (headless).

    freecadcmd cad/freecad/sweep_legs.py

Builds the assembly with build_super_duck.py, then poses left_hip_roll, left_hip_pitch and left_knee over a
grid of angles and checks every moving leg part against the trunk, the hip mount, the (home-pose) right leg
and the other leg links. The right leg is the mirror image. Overlaps already present at home are subtracted.
Writes leg_sweep_report.md.
"""
import itertools
import os
import time

import FreeCAD as App

HERE = os.path.dirname(os.path.abspath(__file__))
_g = {"__file__": os.path.join(HERE, "build_super_duck.py"), "__name__": "__main__"}
exec(open(_g["__file__"]).read(), _g)
B, V, T = _g["B"], _g["V"], _g["T"]

CHAIN = [("left_roll_to_pitch_assembly", "left_hip_roll", (1, 0, 0), "hip_roll_assembly"),
         ("knee_and_ankle_assembly", "left_hip_pitch", (0, 1, 0), "left_roll_to_pitch_assembly"),
         ("knee_and_ankle_assembly_2", "left_knee", (0, 1, 0), "knee_and_ankle_assembly"),
         ("foot_assembly", None, None, "knee_and_ankle_assembly_2")]
GRID = {"left_hip_roll": [-25, 0, 25], "left_hip_pitch": [-30, 0, 30, 50, 70],
        "left_knee": [-90, -60, -30, 0, 30, 60, 90]}
LEVEL = {b: i for i, (b, *_) in enumerate(CHAIN)}

local = {}
for label, body, tag, plc, shape in B.items:
    s = shape.copy()
    s.Placement = plc.multiply(s.Placement)
    local[label] = (body, s)
moving = [k for k, (b, _) in local.items() if b in LEVEL]
static = [k for k, (b, _) in local.items() if b not in LEVEL and not k.startswith("sim_")
          and (b in (T, "hip_roll_assembly", "base") or k.startswith("R_"))]


def chain_world(angles):
    w = {}
    for body, joint, axis, parent in CHAIN:
        p = App.Placement(B.parts[body].Placement.Base, App.Rotation())
        if joint:
            p = p.multiply(App.Placement(V(0, 0, 0), App.Rotation(V(*axis), angles[joint])))
        w[body] = B.world[parent].multiply(p) if parent not in w else w[parent].multiply(p)
    return w


def overlaps(w):
    shapes = {}
    for k in moving + static:
        body, s = local[k]
        out = s.copy()
        out.Placement = (w.get(body) or B.world[body]).multiply(s.Placement)
        shapes[k] = out
    res = {}
    pairs = [(a, b) for a in moving for b in static]
    pairs += [(a, b) for a, b in itertools.combinations(moving, 2) if LEVEL[local[a][0]] != LEVEL[local[b][0]]]
    for a, b in pairs:
        if not shapes[a].BoundBox.intersect(shapes[b].BoundBox):
            continue
        try:
            v = shapes[a].common(shapes[b]).Volume
        except Exception:
            continue
        if v > 1.0:
            res[(a, b)] = v
    return res


t0 = time.time()
home_ang = {"left_hip_roll": 0.0, "left_hip_pitch": _g["HOME"]["left_hip_pitch"], "left_knee": _g["HOME"]["left_knee"]}
home = overlaps(chain_world(home_ang))
worst = {}
bad = set()
poses = list(itertools.product(*GRID.values()))
for i, combo in enumerate(poses):
    ang = dict(zip(GRID, combo))
    for pair, v in overlaps(chain_world(ang)).items():
        grow = v - home.get(pair, 0.0)
        if grow > 5.0:
            bad.add((ang["left_hip_pitch"], ang["left_knee"]))
            if grow > worst.get(pair, (0, None))[0]:
                worst[pair] = (grow, ang)
    print(f"[{time.time() - t0:6.0f} s] pose {i + 1}/{len(poses)} {ang} -> {len(worst)} clashing pairs so far", flush=True)

lines = ["# Leg Sweep Report", "",
         "Generated by `cad/freecad/sweep_legs.py` (left leg; the right is its mirror). Grid: " +
         ", ".join(f"{j} {v}" for j, v in GRID.items()) +
         f" (deg; home is hip_pitch {home_ang['left_hip_pitch']:.1f}, knee {home_ang['left_knee']:.1f}, knees bend "
         "backward). Overlap growth beyond the home pose, mm³.", ""]
if worst:
    lines += ["| Moving part | Other part | Worst growth (mm³) | Pose (hip_roll, hip_pitch, knee) |",
              "| :--- | :--- | ---: | :--- |"]
    for (a, b), (g, ang) in sorted(worst.items(), key=lambda kv: -kv[1][0]):
        lines.append(f"| `{a}` | `{b}` | {g:.0f} | {', '.join(f'{ang[j]:g}' for j in GRID)} |")
    # which poses are clash-free, per (hip_pitch, knee), any roll
    lines += ["", "## Clash-free (hip_pitch x knee, all hip_roll in the grid)", "",
              "| hip_pitch \\ knee | " + " | ".join(f"{k:+d}" for k in GRID["left_knee"]) + " |",
              "| ---: |" + " :---: |" * len(GRID["left_knee"])]
    for hpitch in GRID["left_hip_pitch"]:
        lines.append(f"| {hpitch:+d} | " + " | ".join("x" if (hpitch, k) in bad else "ok" for k in GRID["left_knee"]) + " |")
else:
    lines.append("No collisions anywhere on the grid.")
open(os.path.join(HERE, "leg_sweep_report.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
