"""Clash-free envelope of neck pitch x head pitch (headless, fast).

    freecadcmd cad/freecad/neck_envelope.py

Like sweep_neck.py, but the head is replaced by a conservative proxy (the ODM head's outer silhouette
hull + bounding boxes of the projector pod, antenna holders, SG90s and antennas), so a fine grid takes
minutes instead of an hour. For each (neck_pitch, head_pitch) it reports whether any yaw / roll in the
grid hits the trunk, and what. Writes neck_envelope.md.
"""
import itertools
import os
import time

import FreeCAD as App
import Part

HERE = os.path.dirname(os.path.abspath(__file__))
_g = {"__file__": os.path.join(HERE, "build_super_duck.py"), "__name__": "__main__"}
exec(open(_g["__file__"]).read(), _g)
B, V, T, box = _g["B"], _g["V"], _g["T"], _g["box"]

NECK = list(range(-20, 66, 10)) + [65]
HEADP = list(range(-45, 46, 15))
YAW = [-94.5, 0.0, 94.5]
ROLL = [-30.0, 0.0, 30.0]

# ODM head outer silhouettes (head.stl, mm) -> convex hull proxy in head-mesh coordinates
FRONT_YZ = [(-99.0, 109.7), (99.0, 109.7), (77.4, 169.1), (-77.4, 169.1)]
TOP_XY = [(-79.8, -53.85), (80.7, -98.7), (120.0, -98.7), (120.0, 98.7), (80.7, 98.7), (-79.8, 53.85)]
SIDE_XZ = [(-79.97, 109.7), (120.0, 109.7), (120.0, 169.1), (20.0, 169.1), (-73.52, 148.37)]


def prism(poly, axes, lo=-400, hi=400):
    third = ({"x", "y", "z"} - set(axes)).pop()

    def v3(u, v, w):
        c = {axes[0]: u, axes[1]: v, third: w}
        return V(c["x"], c["y"], c["z"])
    face = Part.Face(Part.makePolygon([v3(u, v, lo) for u, v in poly] + [v3(*poly[0], lo)]))
    return face.extrude(V(*[hi - lo if a == third else 0 for a in "xyz"]))


head_items = {it[0]: it for it in B.items}
hull = prism(FRONT_YZ, "yz").common(prism(TOP_XY, "xy")).common(prism(SIDE_XZ, "xz"))
hull.Placement = head_items["head_shell"][3]          # head-mesh placement in the head frame
proxies = {"head (ODM outer hull)": ("head_assembly", hull)}
for label in ("projector_pod", "L_antenna_sg90", "R_antenna_sg90", "left_antenna_holder", "right_antenna_holder",
              "L_antenna", "R_antenna"):
    _, body, _, plc, shape = head_items[label]
    s = shape.copy()
    s.Placement = plc.multiply(s.Placement)
    bb = s.BoundBox
    proxies[label] = (body, box(bb.XMin, bb.XMax, bb.YMin, bb.YMax, bb.ZMin, bb.ZMax) if label == "projector_pod" else s)

trunk = {}
for label, body, tag, plc, shape in B.items:
    if body == T and label not in ("sts3215_neck_pitch", "neck_servo_pocket"):
        s = shape.copy()
        s.Placement = B.world[T].multiply(plc.multiply(s.Placement))
        trunk[label] = s

CHAIN = [("neck_pitch_assembly", "neck_pitch", (0, 1, 0), None), ("head_pitch_to_yaw", "head_pitch", (0, 1, 0), "neck_pitch_assembly"),
         ("neck_yaw_assembly", "head_yaw", (0, 0, 1), "head_pitch_to_yaw"), ("head_assembly", "head_roll", (1, 0, 0), "neck_yaw_assembly"),
         ("left_antenna", None, None, "head_assembly"), ("right_antenna", None, None, "head_assembly")]


def world(ang):
    w = {}
    for body, joint, axis, parent in CHAIN:
        p = App.Placement(B.parts[body].Placement.Base, App.Rotation())
        if joint:
            p = p.multiply(App.Placement(V(0, 0, 0), App.Rotation(V(*axis), ang[joint])))
        w[body] = (w[parent] if parent else B.world[T]).multiply(p)
    return w


def hits(ang):
    w = world(ang)
    out = set()
    for name, (body, s) in proxies.items():
        ps = s.copy()
        ps.Placement = w[body].multiply(s.Placement)
        for tl, ts in trunk.items():
            if ps.BoundBox.intersect(ts.BoundBox) and ps.common(ts).Volume > 2.0:
                out.add(f"{name} / {tl}")
    return out


t0 = time.time()
grid = {}
for n, h in itertools.product(NECK, HEADP):
    found = {}
    for y, r in itertools.product(YAW, ROLL):
        for hit in hits({"neck_pitch": n, "head_pitch": h, "head_yaw": y, "head_roll": r}):
            found.setdefault(hit, (y, r))
    grid[(n, h)] = found
    print(f"[{time.time() - t0:5.0f} s] neck {n:4} head {h:4}: {'ok' if not found else sorted(found)[:3]}", flush=True)

L = ["# Neck Pitch x Head Pitch Envelope", "",
     "Generated by `cad/freecad/neck_envelope.py`. `ok` = no part of the head (conservative proxy: the ODM head's outer hull,",
     f"projector pod box, antenna parts) touches the trunk for any head yaw in {YAW} and roll in {ROLL} (deg). `x` = it does.", "",
     "| neck_pitch \\ head_pitch | " + " | ".join(f"{h:+d}" for h in HEADP) + " |",
     "| ---: |" + " :---: |" * len(HEADP)]
for n in NECK:
    L.append(f"| {n:+d} | " + " | ".join("ok" if not grid[(n, h)] else "x" for h in HEADP) + " |")
L += ["", "## What hits", "", "| neck_pitch | head_pitch | Contacts (first yaw, roll) |", "| ---: | ---: | :--- |"]
for (n, h), found in sorted(grid.items()):
    if found:
        L.append(f"| {n:+d} | {h:+d} | " + "; ".join(f"{k} ({y:g}, {r:g})" for k, (y, r) in sorted(found.items())) + " |")
open(os.path.join(HERE, "neck_envelope.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L[:6 + len(NECK)]))
