"""Sweep the neck / head joints through their ranges and report collisions (headless).

    freecadcmd cad/freecad/sweep_neck.py

Builds the assembly with build_super_duck.py, then poses neck_pitch, head_pitch, head_yaw and head_roll
over a grid of angles (the MJCF ranges; yaw at the controller clip) and checks every moving part against
the trunk and against the other neck links. Overlaps already present at home (ODM press fits) are
subtracted. Writes neck_sweep_report.md.
"""
import itertools
import os
import time

import FreeCAD as App

HERE = os.path.dirname(os.path.abspath(__file__))
_g = {"__file__": os.path.join(HERE, "build_super_duck.py"), "__name__": "__main__"}
exec(open(_g["__file__"]).read(), _g)
B, V, JOINTS, T = _g["B"], _g["V"], _g["JOINTS"], _g["T"]

CHAIN = [("neck_pitch_assembly", "neck_pitch", (0, 1, 0), None),
         ("head_pitch_to_yaw", "head_pitch", (0, 1, 0), "neck_pitch_assembly"),
         ("neck_yaw_assembly", "head_yaw", (0, 0, 1), "head_pitch_to_yaw"),
         ("head_assembly", "head_roll", (1, 0, 0), "neck_yaw_assembly"),
         ("left_antenna", None, None, "head_assembly"),
         ("right_antenna", None, None, "head_assembly")]
GRID = {"neck_pitch": [-20, 0, 30, 65], "head_pitch": [-45, 0, 45],
        "head_yaw": [-94.5, 0, 94.5], "head_roll": [-30, 0, 30]}
LEVEL = {b: i for i, (b, *_) in enumerate(CHAIN)}
LEVEL["left_antenna"] = LEVEL["right_antenna"] = LEVEL["head_assembly"]

# shapes in their body frames
local = {}
for label, body, tag, plc, shape in B.items:
    s = shape.copy()
    s.Placement = plc.multiply(s.Placement)
    local[label] = (body, s)
moving = [k for k, (b, _) in local.items() if b in LEVEL]
static = [k for k, (b, _) in local.items() if b not in LEVEL and b.startswith(("trunk", "hip_roll", "base"))]


def chain_world(angles):
    w = {}
    for body, joint, axis, parent in CHAIN:
        p = App.Placement(B.parts[body].Placement.Base, App.Rotation())
        if joint:
            p = p.multiply(App.Placement(V(0, 0, 0), App.Rotation(V(*axis), angles[joint])))
        w[body] = (w[parent] if parent else B.world[T]).multiply(p)
    return w


def placed(label, w):
    body, s = local[label]
    out = s.copy()
    out.Placement = (w.get(body) or B.world[body]).multiply(s.Placement)
    return out


def overlaps(w):
    shapes = {k: placed(k, w) for k in moving + static}
    res = {}
    pairs = [(a, b) for a in moving for b in static]
    pairs += [(a, b) for a, b in itertools.combinations(moving, 2) if LEVEL[local[a][0]] != LEVEL[local[b][0]]]
    for a, b in pairs:
        if not shapes[a].BoundBox.intersect(shapes[b].BoundBox):
            continue
        try:
            v = shapes[a].common(shapes[b]).Volume
        except Exception:
            continue
        if v > 1.0:
            res[(a, b)] = v
    return res


t0 = time.time()
home = overlaps(chain_world({j: 0.0 for j in GRID}))
worst = {}
poses = list(itertools.product(*GRID.values()))
for i, combo in enumerate(poses):
    ang = dict(zip(GRID, combo))
    for pair, v in overlaps(chain_world(ang)).items():
        grow = v - home.get(pair, 0.0)
        if grow > 5.0 and grow > worst.get(pair, (0, None))[0]:
            worst[pair] = (grow, ang)
    print(f"[{time.time() - t0:6.0f} s] pose {i + 1}/{len(poses)} {ang} -> {len(worst)} clashing pairs so far", flush=True)

lines = ["# Neck Sweep Report", "",
         "Generated by `cad/freecad/sweep_neck.py`. Grid: " +
         ", ".join(f"{j} {v}" for j, v in GRID.items()) + " (deg). Overlap growth beyond the home pose, mm³.", ""]
if worst:
    lines += ["| Moving part | Other part | Worst growth (mm³) | Pose (neck_pitch, head_pitch, head_yaw, head_roll) |",
              "| :--- | :--- | ---: | :--- |"]
    for (a, b), (g, ang) in sorted(worst.items(), key=lambda kv: -kv[1][0]):
        lines.append(f"| `{a}` | `{b}` | {g:.0f} | {', '.join(f'{ang[j]:g}' for j in GRID)} |")
else:
    lines.append("No collisions anywhere on the grid.")
open(os.path.join(HERE, "neck_sweep_report.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
